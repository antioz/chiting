// Запасной крючок для неизвестной комбинации правила и типа (новые правила/типы — фаза 2).
const FALLBACK = [
  'Попробуй ещё раз — медленнее, своими словами.',
  'А что здесь самое главное? Скажи это одной фразой.',
  'Перечитай вопрос и попробуй ответить короче и точнее.',
];

function variants(ruleCode, qType) {
  const byRule = MATRIX[ruleCode];
  const v = byRule && byRule[qType];
  return v && v.length ? v : FALLBACK;
}

// idx — сколько подсказок уже выдано на этот qid (по кругу).
function pick(ruleCode, qType, idx) {
  const v = variants(ruleCode, qType);
  return v[Number(idx || 0) % v.length];
}

